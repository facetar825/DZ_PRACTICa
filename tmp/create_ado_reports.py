for folder, marker, title, summary, answers, practice in entries:
    dest=root/folder
    dest.mkdir(exist_ok=True)
    (dest/'Homework.csproj').write_text('<Project Sdk="Microsoft.NET.Sdk" />\n', encoding='utf-8')
    markers = ['Введение', 'Провайдеры', 'SqlCommand', 'SqlParameter', 'SqlDataReader', 'Транзакции', 'Асинхронная', 'DataTable']
    marker = markers[int(folder[:2])-1]
    source=next(p for p in sources.glob('*.txt') if marker in p.name)
    text=source.read_text(encoding='utf-8').replace('\x00','')
    block=text.split('Вопросы  для  самопроверки')[-1].split('Небольшое  самостоятельное  задание')[0]
    block=re.sub(r' +',' ',block)
    # Вопросы сохраняются из исходного PDF; ответы идут в том же порядке.
    block='\n'.join(line for line in block.splitlines() if line.strip() and not line.strip().isdigit() and line.strip() not in (title,title.replace('- ',': ')))
    questions=re.findall(r'[^?]+\?', block)
    block='\n\n'.join(f'{i}. {" ".join(q.split())}' for i,q in enumerate(questions,1))
